-- SYSTEMIC RISK SIMULATOR: COMPLETE POSTGRESQL CREATION QUERIES
-- This is the annotated version of schema.sql, used by backend.setup_db.
-- It includes all 10 tables, constraints, ALTER statements, indexes, view,
-- stored functions and audit triggers. No existing tables/data are deleted.
--
-- DATABASE CREATION (only when setting up a NEW database manually):
-- Docker Compose already creates systemic_risk, owned by simulator.
-- Otherwise, connect to the postgres database in pgAdmin and run this ONE
-- statement separately, with auto-commit enabled and the simulator role present:
-- CREATE DATABASE systemic_risk OWNER simulator;
-- Then open Query Tool on systemic_risk and execute the statements below.
-- CREATE DATABASE cannot run inside a transaction block.
--
-- EXISTING PROJECT: these definitions are already applied. You can inspect
-- this file without executing it. Initial fictional data is in sql/seed.sql;
-- account password hashes are created by backend.seed_users.

-- 1. BANKS: identity PK, unique name, positive liquidity buffer.
CREATE TABLE IF NOT EXISTS institutions (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE,
    liquidity_buffer numeric(14,2) NOT NULL CHECK (liquidity_buffer > 0)
);

-- 2. SERVICES: identity PK and unique service name.
CREATE TABLE IF NOT EXISTS infrastructure (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE,
    category text NOT NULL
);

-- 3. USERS: unique email, valid role, non-blank display name and defaults.
CREATE TABLE IF NOT EXISTS users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 100),
    email text NOT NULL UNIQUE,
    password_hash text NOT NULL,
    role text NOT NULL CHECK (role IN ('admin', 'analyst')),
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- 4. SESSIONS: deleting a user also removes their sessions (CASCADE).
CREATE TABLE IF NOT EXISTS user_sessions (
    token_hash text PRIMARY KEY,
    user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at timestamptz NOT NULL
);

-- 5. BANK/SERVICE DEPENDENCIES: composite PK prevents duplicate pairs.
-- RESTRICT prevents deleting a bank/service while dependencies refer to it.
CREATE TABLE IF NOT EXISTS dependencies (
    institution_id integer NOT NULL REFERENCES institutions(id) ON DELETE RESTRICT,
    infrastructure_id integer NOT NULL REFERENCES infrastructure(id) ON DELETE RESTRICT,
    loss_at_full_failure numeric(14,2) NOT NULL CHECK (loss_at_full_failure >= 0),
    PRIMARY KEY (institution_id, infrastructure_id)
);

-- 6. FINANCIAL EXPOSURES: both FKs point to banks, in different roles.
-- A bank cannot lend to itself; amounts are non-negative; recovery is 0..1.
CREATE TABLE IF NOT EXISTS exposures (
    creditor_id integer NOT NULL REFERENCES institutions(id) ON DELETE RESTRICT,
    debtor_id integer NOT NULL REFERENCES institutions(id) ON DELETE RESTRICT,
    amount numeric(14,2) NOT NULL CHECK (amount >= 0),
    recovery_rate numeric(4,3) NOT NULL CHECK (recovery_rate BETWEEN 0 AND 1),
    PRIMARY KEY (creditor_id, debtor_id),
    CHECK (creditor_id <> debtor_id)
);

-- 7. SCENARIOS: failed service FK, valid severity and non-blank name.
-- For multi-service runs, this row stores the primary/first failed service.
-- The complete failure list is preserved in simulation_runs.input_snapshot.
CREATE TABLE IF NOT EXISTS scenarios (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 100),
    failed_infrastructure_id integer NOT NULL REFERENCES infrastructure(id) ON DELETE RESTRICT,
    severity integer NOT NULL CHECK (severity BETWEEN 0 AND 100),
    created_at timestamptz NOT NULL DEFAULT now()
);

-- ALTER adds ownership while allowing existing older scenario rows.
ALTER TABLE scenarios ADD COLUMN IF NOT EXISTS owner_id
    integer REFERENCES users(id) ON DELETE RESTRICT;

-- 8. RUNS: each execution belongs to a scenario and stores its input snapshot.
CREATE TABLE IF NOT EXISTS simulation_runs (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scenario_id integer NOT NULL REFERENCES scenarios(id) ON DELETE RESTRICT,
    created_at timestamptz NOT NULL DEFAULT now(),
    risk_score numeric(6,2) NOT NULL CHECK (risk_score BETWEEN 0 AND 100),
    default_count integer NOT NULL CHECK (default_count >= 0),
    input_snapshot jsonb NOT NULL
);

-- Creator, optional self-referencing baseline, and buffer-comparison details.
ALTER TABLE simulation_runs ADD COLUMN IF NOT EXISTS created_by
    integer REFERENCES users(id) ON DELETE RESTRICT;
ALTER TABLE simulation_runs ADD COLUMN IF NOT EXISTS baseline_run_id
    integer REFERENCES simulation_runs(id) ON DELETE RESTRICT;
ALTER TABLE simulation_runs ADD COLUMN IF NOT EXISTS mitigation_bank_id
    integer REFERENCES institutions(id) ON DELETE RESTRICT;
ALTER TABLE simulation_runs ADD COLUMN IF NOT EXISTS extra_buffer
    numeric(14,2) CHECK (extra_buffer > 0);
ALTER TABLE simulation_runs ADD COLUMN IF NOT EXISTS formula_version
    integer NOT NULL DEFAULT 1;
ALTER TABLE simulation_runs ADD COLUMN IF NOT EXISTS failed_service_name text;

-- 9. BANK RESULTS: composite PK allows one result per bank per run.
-- Deleting a run cascades to its impacts; referenced banks are protected.
CREATE TABLE IF NOT EXISTS run_impacts (
    run_id integer NOT NULL REFERENCES simulation_runs(id) ON DELETE CASCADE,
    institution_id integer NOT NULL REFERENCES institutions(id) ON DELETE RESTRICT,
    first_affected_round integer CHECK (first_affected_round >= 0),
    operational_loss numeric(14,2) NOT NULL CHECK (operational_loss >= 0),
    financial_loss numeric(14,2) NOT NULL CHECK (financial_loss >= 0),
    stress_pct numeric(6,2) NOT NULL CHECK (stress_pct BETWEEN 0 AND 100),
    defaulted boolean NOT NULL,
    PRIMARY KEY (run_id, institution_id)
);

ALTER TABLE run_impacts ADD COLUMN IF NOT EXISTS propagation_path
    jsonb NOT NULL DEFAULT '[]'::jsonb;
ALTER TABLE run_impacts ADD COLUMN IF NOT EXISTS bank_name_at_run text;

-- 10. AUDIT HISTORY: preserve audit rows if their actor is deleted (SET NULL).
-- record_id is generic: its referenced table is recorded in table_name.
CREATE TABLE IF NOT EXISTS audit_logs (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    changed_at timestamptz NOT NULL DEFAULT now(),
    actor_id integer REFERENCES users(id) ON DELETE SET NULL,
    table_name text NOT NULL,
    action text NOT NULL CHECK (action IN ('INSERT', 'UPDATE', 'DELETE')),
    record_id integer NOT NULL,
    old_data jsonb,
    new_data jsonb
);

-- 11. INDEXES: support history, exposure, ownership, session and audit queries.
-- PK and UNIQUE constraints also create their own indexes automatically.
CREATE INDEX IF NOT EXISTS idx_runs_scenario_created
    ON simulation_runs(scenario_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_exposures_debtor ON exposures(debtor_id);
CREATE INDEX IF NOT EXISTS idx_scenarios_owner_created ON scenarios(owner_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_sessions_user_expires ON user_sessions(user_id, expires_at);
CREATE INDEX IF NOT EXISTS idx_audit_changed_at ON audit_logs(changed_at DESC);

-- 12. VIEW: joined summary used by the dashboard and saved-run history.
CREATE OR REPLACE VIEW v_run_summary AS
SELECT r.id AS run_id, r.created_at, s.name AS scenario_name,
       COALESCE(r.failed_service_name, i.name) AS failed_service,
       s.severity, r.risk_score, r.default_count,
       s.owner_id, r.created_by, r.baseline_run_id, r.mitigation_bank_id,
       r.extra_buffer, r.formula_version, u.name AS creator_name
FROM simulation_runs r
JOIN scenarios s ON s.id = r.scenario_id
JOIN infrastructure i ON i.id = s.failed_infrastructure_id
LEFT JOIN users u ON u.id = r.created_by;

-- 13. STORED FUNCTION: average saved bank stress, rounded to two decimals.
CREATE OR REPLACE FUNCTION calculate_systemic_risk(p_run_id integer)
RETURNS numeric LANGUAGE sql STABLE AS $$
    SELECT ROUND(COALESCE(AVG(stress_pct), 0), 2)
    FROM run_impacts WHERE run_id = p_run_id
$$;

-- 14. TRIGGER FUNCTION: capture INSERT/UPDATE/DELETE details and actor.
-- The backend sets app.user_id within its transaction for Admin edits.
CREATE OR REPLACE FUNCTION audit_master_data()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    v_actor integer;
    v_id integer;
    v_old jsonb;
    v_new jsonb;
BEGIN
    v_actor := NULLIF(current_setting('app.user_id', true), '')::integer;
    IF TG_OP = 'DELETE' THEN
        v_id := OLD.id;
        v_old := to_jsonb(OLD);
        v_new := NULL;
    ELSIF TG_OP = 'INSERT' THEN
        v_id := NEW.id;
        v_old := NULL;
        v_new := to_jsonb(NEW);
    ELSE
        v_id := NEW.id;
        v_old := to_jsonb(OLD);
        v_new := to_jsonb(NEW);
    END IF;
    INSERT INTO audit_logs (actor_id, table_name, action, record_id, old_data, new_data)
    VALUES (v_actor, TG_TABLE_NAME, TG_OP, v_id, v_old, v_new);
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END
$$;

-- 15. TRIGGERS: run the audit function after each bank/service change.
-- Replacing these trigger definitions does not delete existing audit rows.
DROP TRIGGER IF EXISTS audit_institutions ON institutions;
CREATE TRIGGER audit_institutions AFTER INSERT OR UPDATE OR DELETE ON institutions
FOR EACH ROW EXECUTE FUNCTION audit_master_data();
DROP TRIGGER IF EXISTS audit_infrastructure ON infrastructure;
CREATE TRIGGER audit_infrastructure AFTER INSERT OR UPDATE OR DELETE ON infrastructure
FOR EACH ROW EXECUTE FUNCTION audit_master_data();
